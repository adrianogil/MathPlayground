// Run with Node to rebuild the deterministic, exhaustively checked puzzle bank.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const E = require('./engine.js');
let seed = 6767;
const random = () => { seed = (Math.imul(1664525, seed) + 1013904223) >>> 0; return seed / 4294967296; };
const int = (a, b) => a + Math.floor(random() * (b - a + 1));
const bank = [];
for (let level = 1; level <= 4; level++) {
  const puzzles = [], seen = new Set();
  for (let attempts = 0; puzzles.length < 24 && attempts < 20000; attempts++) {
    let numbers, ops;
    if (level === 1) {
      const a = int(7, 60);
      numbers = [a, 67 - a]; ops = ['+'];
    } else if (level === 2) {
      const a = int(3, 12), b = int(3, 12);
      const subtract = a * b > 67;
      numbers = [a, b, Math.abs(67 - a * b)]; ops = ['*', subtract ? '-' : '+'];
    } else {
      const a = int(3, 25), b = int(3, 25), c = int(3, 9), e = level === 4 ? int(2, 5) : 1;
      numbers = [a, b, c, (a + b) * c - 67 * e]; ops = ['+', '*', '-'];
      if (level === 4) { numbers.push(e); ops.push('/'); }
    }
    if (numbers.some(n => n < 2 || n > (level === 1 ? 60 : 36))) continue;
    const key = [...numbers].sort((a, b) => a - b).join(',') + ':' + ops.join('');
    if (seen.has(key)) continue;
    seen.add(key);
    if (E.countSolutions(E.createState(numbers, ops)) === 1) puzzles.push({ numbers, ops });
  }
  if (puzzles.length !== 24) throw new Error(`Insufficient unique puzzles at level ${level}`);
  bank.push(puzzles);
  console.log(`Level ${level}: ${puzzles.length} uniquely solvable puzzles`);
}
const source = `// Generated by build-puzzles.js; every entry is checked again by engine.test.js.\n(function (root) {\n  'use strict';\n  const puzzles = ${JSON.stringify(bank, null, 2)};\n  if (typeof module !== 'undefined' && module.exports) module.exports = puzzles;\n  else root.SixtySevenPuzzles = puzzles;\n})(typeof globalThis !== 'undefined' ? globalThis : this);\n`;
fs.writeFileSync(path.join(__dirname, 'puzzles.js'), source);
